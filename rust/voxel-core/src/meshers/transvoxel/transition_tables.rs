//! `meshers/transvoxel/transvoxel_tables.cpp` (Eric Lengyel's Transvoxel
//! Algorithm, Section 4.3). These tables drive the LOD seam mesher — the
//! transition-cell path that stitches a high-resolution voxel block to its
//! low-resolution neighbour so the rendered surface stays watertight across
//! LOD boundaries (audit §M2.2).
//!
