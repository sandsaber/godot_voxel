//! license note in the original C++ file: the data may be freely used in
//! Transvoxel implementations provided credit is given in source code.

/// Per-class triangulation data for a transition cell. Mirrors C++
/// `TransitionCellData`. The high nibble of `geometry_counts` is the vertex
/// count; the low nibble is the triangle count.
#[derive(Debug, Clone, Copy)]
#[repr(C)]
pub struct TransitionCellData {
    /// High nibble = vertex count, low nibble = triangle count.
    pub geometry_counts: u8,
    /// Vertex indices grouped in triples forming triangles. Unused
    /// trailing entries are zero; the largest class uses all 36.
    pub vertex_index: [u8; 36],
}

impl TransitionCellData {
    #[inline]
    pub fn triangle_count(self) -> u8 {
        self.geometry_counts & 0x0F
    }
    #[inline]
    pub fn vertex_count(self) -> u8 {
        (self.geometry_counts & 0xF0) >> 4
    }
    #[inline]
    pub fn get_vertex_index(self, i: usize) -> u8 {
        debug_assert!(i < 36);
        self.vertex_index[i]
    }
}

