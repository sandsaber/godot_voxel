/// Lookup for `TRANSITION_CELL_CLASS[case_index]`. Returns the equivalence
/// class (lower 7 bits) with the winding-reversal flag in bit 7.
#[inline]
pub fn get_transition_cell_class(case_index: usize) -> u8 {
    debug_assert!(case_index < 512);
    TRANSITION_CELL_CLASS[case_index]
}

/// Lookup for `TRANSITION_CELL_DATA[class_index]`. Callers should mask the
/// class with `& 0x7F` before indexing.
#[inline]
pub fn get_transition_cell_data(class_index: usize) -> &'static TransitionCellData {
    debug_assert!(class_index < 56);
    &TRANSITION_CELL_DATA[class_index]
}

/// Lookup for `TRANSITION_CORNER_DATA[i]`.
#[inline]
pub fn get_transition_corner_data(i: usize) -> u8 {
    debug_assert!(i < 13);
    TRANSITION_CORNER_DATA[i]
}

/// Lookup for `TRANSITION_VERTEX_DATA[i][j]`.
#[inline]
pub fn get_transition_vertex_data(i: usize, j: usize) -> u16 {
    debug_assert!(i < 512);
    debug_assert!(j < 12);
    TRANSITION_VERTEX_DATA[i][j]
}

